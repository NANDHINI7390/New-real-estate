// Formatting utilities for INR
export function formatINR(amount: number): string {
  if (amount >= 10000000) {
    const cr = amount / 10000000;
    return `₹ ${cr.toFixed(2).replace(/\.00$/, '')} Cr`;
  }
  if (amount >= 100000) {
    const l = amount / 100000;
    return `₹ ${l.toFixed(2).replace(/\.00$/, '')} L`;
  }
  return `₹ ${amount.toLocaleString('en-IN')}`;
}

export function calculateEMI(
  principal: number,
  annualInterestRate: number = 8.5,
  tenureYears: number = 20
): {
  monthlyEMI: number;
  totalInterest: number;
  totalAmount: number;
} {
  const monthlyRate = annualInterestRate / 12 / 100;
  const totalMonths = tenureYears * 12;

  if (principal <= 0 || monthlyRate <= 0 || totalMonths <= 0) {
    return { monthlyEMI: 0, totalInterest: 0, totalAmount: 0 };
  }

  const emi =
    (principal * monthlyRate * Math.pow(1 + monthlyRate, totalMonths)) /
    (Math.pow(1 + monthlyRate, totalMonths) - 1);

  const totalAmount = emi * totalMonths;
  const totalInterest = totalAmount - principal;

  return {
    monthlyEMI: Math.round(emi),
    totalInterest: Math.round(totalInterest),
    totalAmount: Math.round(totalAmount),
  };
}
